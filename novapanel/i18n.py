lang = "en"


def system_language():
    try:
        from PySide6.QtCore import QLocale
        langs = QLocale.system().uiLanguages()
        if langs and langs[0] != "C":
            return langs[0]
    except ImportError:
        pass
    return os.environ.get("LC_ALL") or os.environ.get("LANG") or locale.getlocale()[0] or ""


def resolve(setting, system=None):
    if setting in STRINGS:
        return setting
    return "fr" if (system if system is not None else system_language()).lower().startswith("fr") else "en"


def set_language(setting):
    global lang
    lang = resolve(setting)


def t(key, **kw):
    s = STRINGS[lang][key]
    return s.format(**kw) if kw else s
